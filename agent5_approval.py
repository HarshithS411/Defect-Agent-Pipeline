"""
AGENT 5 — Approval + Commit/PR
--------------------------------
Takes a validated fix (from Agent 4), shows the diff, and asks for your
approval right in the terminal.

On approval:
  - If GITHUB_TOKEN + GITHUB_REPO are set: creates a branch, pushes it,
    opens a PR via the GitHub API, and merges it. Since you already
    approved in the terminal, the merge happens immediately — you still
    get a real PR on GitHub as a record, you just don't have to also
    click "merge" there.
  - Otherwise (no GitHub token configured yet): commits and pushes the fix
    directly to whatever branch is currently checked out. This is the
    documented fallback — "if PR creation isn't possible, commit directly
    once approved."

On rejection: nothing is written to the real repo at all.

Either way a successful commit/merge also writes the resolved ticket + fix
into the `solutions` table, so Agent 2/Agent 3 can reference it for
similar tickets in the future.
"""

import os
import subprocess
import sys
from pathlib import Path

from dotenv import load_dotenv
from jira import JIRA
from langchain_ollama import OllamaEmbeddings

import db
from agent1_parser import parse_ticket
from agent2_scanner import scan_codebase
from agent3_fix_generator import show_diff
from agent4_validator import validate_with_retries

load_dotenv()

REPO_PATH = os.getenv("MINISHOP_REPO_PATH")
GITHUB_TOKEN = os.getenv("GITHUB_TOKEN")
GITHUB_REPO = os.getenv("GITHUB_REPO")  # e.g. "yourusername/minishop"

JIRA_URL = os.getenv("JIRA_URL")
JIRA_EMAIL = os.getenv("JIRA_EMAIL")
JIRA_API_TOKEN = os.getenv("JIRA_API_TOKEN")

# Status names to try transitioning a resolved ticket to, in order of
# preference — whichever one actually exists in your Jira workflow wins.
# If none of these match your workflow's transition names, the comment
# still gets posted; the status is just left as-is.
RESOLVED_STATUS_NAMES = ("done", "resolved", "closed")

embedder = OllamaEmbeddings(model="mxbai-embed-large")


def _run_git(args: list[str], cwd: str) -> str:
    result = subprocess.run(
        ["git"] + args, cwd=cwd, capture_output=True, text=True, check=True
    )
    return result.stdout.strip()


def _apply_fix_to_real_repo(fix: dict) -> Path:
    """Writes the fix into the ACTUAL repo on disk. Only ever called after
    terminal approval — never before."""
    target_file = Path(REPO_PATH) / fix["file_path"]
    content = target_file.read_text(encoding="utf-8")
    if fix["original_code"] not in content:
        raise ValueError(
            f"Could not find the original function text in {fix['file_path']} "
            "— the real file may have changed since this fix was generated."
        )
    patched = content.replace(fix["original_code"], fix["fixed_code"], 1)
    target_file.write_text(patched, encoding="utf-8")
    return target_file


def commit_via_pull_request(ticket_key: str, fix: dict) -> str:
    """Branch -> apply fix -> commit -> push -> open PR -> merge.
    Returns the PR url."""
    from github import Auth, Github  # PyGithub

    branch_name = f"fix/{ticket_key.lower()}"

    _run_git(["checkout", "main"], REPO_PATH)
    _run_git(["pull"], REPO_PATH)
    _run_git(["checkout", "-b", branch_name], REPO_PATH)

    _apply_fix_to_real_repo(fix)

    _run_git(["add", fix["file_path"]], REPO_PATH)
    _run_git(
        ["commit", "-m", f"Fix {ticket_key}: {fix['function_name']}() patched by defect agent"],
        REPO_PATH,
    )
    _run_git(["push", "-u", "origin", branch_name], REPO_PATH)

    gh = Github(auth=Auth.Token(GITHUB_TOKEN))
    repo = gh.get_repo(GITHUB_REPO)
    pr = repo.create_pull(
        title=f"Fix {ticket_key}: {fix['function_name']}()",
        body=(
            f"Automated fix generated by the defect-resolution agent for {ticket_key}.\n\n"
            f"Approved via terminal by operator before merge."
        ),
        head=branch_name,
        base="main",
    )
    pr.merge(commit_message=f"Merge fix for {ticket_key}", merge_method="squash")

    _run_git(["checkout", "main"], REPO_PATH)
    _run_git(["pull"], REPO_PATH)

    return pr.html_url


def commit_directly(ticket_key: str, fix: dict) -> None:
    """Fallback when GitHub PR automation isn't configured: commit straight
    to whatever branch is currently checked out and push."""
    _apply_fix_to_real_repo(fix)
    _run_git(["add", fix["file_path"]], REPO_PATH)
    _run_git(
        ["commit", "-m", f"Fix {ticket_key}: {fix['function_name']}() patched by defect agent"],
        REPO_PATH,
    )
    _run_git(["push"], REPO_PATH)


def save_to_knowledge_base(ticket_key: str, parsed_ticket: dict, fix: dict, pr_url: str | None) -> None:
    problem_text = f"{parsed_ticket['summary']}\n{parsed_ticket['description']}"
    embedding = embedder.embed_query(problem_text)
    diff_text = show_diff(fix["original_code"], fix["fixed_code"])

    db.insert_solution(
        ticket_key=ticket_key,
        component=parsed_ticket.get("component") or "Unknown",
        problem_summary=parsed_ticket["summary"],
        solution_summary=diff_text,
        file_path=fix["file_path"],
        function_name=fix["function_name"],
        embedding=embedding,
    )

    db.insert_resolution(
        ticket_key=ticket_key,
        final_file=fix["file_path"],
        final_function=fix["function_name"],
        final_diff=diff_text,
        pr_url=pr_url,
        approved=True,
    )


def update_jira_ticket(ticket_key: str, approved: bool, pr_url: str | None) -> None:
    """Writes the outcome back onto the Jira ticket: a comment always, and
    (only if approved) an attempt to transition the ticket to a resolved
    status. A missing/renamed transition in your workflow is not an error —
    the comment still posts, the status is just left as-is."""
    jira = JIRA(server=JIRA_URL, basic_auth=(JIRA_EMAIL, JIRA_API_TOKEN))
    issue = jira.issue(ticket_key)

    if approved:
        comment = "✅ Automatically resolved by the defect-resolution agent."
        comment += (
            f"\n\nFix merged via PR: {pr_url}" if pr_url
            else "\n\nFix committed directly (no GitHub PR configured)."
        )
    else:
        comment = (
            "⚠️ The defect-resolution agent generated a fix for this ticket, "
            "but it was rejected during human review and was NOT applied. "
            "Manual investigation still needed."
        )

    jira.add_comment(issue, comment)

    if approved:
        try:
            transitions = jira.transitions(issue)
            match = next(
                (t for t in transitions if t["name"].strip().lower() in RESOLVED_STATUS_NAMES),
                None,
            )
            if match:
                jira.transition_issue(issue, match["id"])
            else:
                print(f"(No matching 'Done/Resolved/Closed' transition found in your "
                      f"workflow for {ticket_key} — comment posted, status unchanged.)")
        except Exception as e:
            print(f"(Could not auto-transition {ticket_key}'s status: {e})")


def run_agent5(ticket_key: str, parsed_ticket: dict, fix: dict) -> None:
    print("\n=== Proposed fix ready for approval ===")
    print(f"File: {fix['file_path']}   Function: {fix['function_name']}()\n")
    print(show_diff(fix["original_code"], fix["fixed_code"]))

    decision = input("\nApprove and commit this fix? [y/N]: ").strip().lower()

    if decision != "y":
        print("Rejected — nothing written to the repo.")
        db.insert_resolution(
            ticket_key=ticket_key,
            final_file=fix["file_path"],
            final_function=fix["function_name"],
            final_diff=show_diff(fix["original_code"], fix["fixed_code"]),
            pr_url=None,
            approved=False,
        )
        update_jira_ticket(ticket_key, approved=False, pr_url=None)
        return

    pr_url = None
    try:
        if GITHUB_TOKEN and GITHUB_REPO:
            print("Creating branch, pushing, opening + merging PR...")
            pr_url = commit_via_pull_request(ticket_key, fix)
            print(f"✅ Merged via PR: {pr_url}")
        else:
            print("GITHUB_TOKEN/GITHUB_REPO not set — committing directly instead.")
            commit_directly(ticket_key, fix)
            print("✅ Committed and pushed directly.")
    except Exception as e:
        print(f"❌ Commit/PR step failed: {e}")
        print("Nothing recorded as resolved — check the repo state manually before retrying.")
        return

    save_to_knowledge_base(ticket_key, parsed_ticket, fix, pr_url)
    print("📚 Saved to the knowledge base (solutions table).")

    update_jira_ticket(ticket_key, approved=True, pr_url=pr_url)
    print(f"📝 Posted resolution comment on {ticket_key}.")


if __name__ == "__main__":
    ticket_key = os.getenv("TICKET_KEY", "SCRUM-6")

    parsed = parse_ticket(ticket_key)
    candidates = scan_codebase(parsed)

    if not candidates:
        print("No candidate functions found by Agent 2.")
        sys.exit(1)

    top = candidates[0]
    result = validate_with_retries(parsed, top, REPO_PATH)

    if not result["success"]:
        print(f"\n❌ No passing fix found after {result['attempts']} attempts — nothing to approve.")
        if result.get("fix"):
            print("\n=== Last attempted fix (diff) ===")
            print(show_diff(result["fix"]["original_code"], result["fix"]["fixed_code"]))
        print("\n=== Last test output ===")
        print(result["test_output"])
        sys.exit(1)

    run_agent5(ticket_key, parsed, result["fix"])